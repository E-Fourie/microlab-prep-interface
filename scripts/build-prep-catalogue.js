#!/usr/bin/env node
// Builds web/prep-catalogue.js from the two files the Prep Interface
// exports from the machine (labware_catalogue.json and liquid_classes.json).
//
//   node scripts/build-prep-catalogue.js <folder holding the two json files>
//
// Only what the Builder can use is kept: plates (more than one well), tip racks and
// 24-position tube racks, each under the key c_<Prep id>, plus the ids the built-in keys
// (tips_300, plate_pcr, ...) stand for. The selection rules match labware_map.builder_defs()
// in the Prep Interface repo, so the Builder and the converter agree on what exists.
const fs = require('fs');
const path = require('path');

const dir = process.argv[2];
if (!dir) { console.error('usage: node scripts/build-prep-catalogue.js <folder with labware_catalogue.json and liquid_classes.json>'); process.exit(1); }
const cat = JSON.parse(fs.readFileSync(path.join(dir, 'labware_catalogue.json'), 'utf8')).labware;
const liq = JSON.parse(fs.readFileSync(path.join(dir, 'liquid_classes.json'), 'utf8')).liquids;

// The built-in Builder keys and the catalogue entry (its `name`) each one is compiled to. Same table as labware_map.BUILTIN.
const BUILTIN = {
  tips_50: '235966', tips_300: '235902', tips_1000: '235904',
  plate_pcr: 'P96w200jjxtwHAM', plate_deep: 'DW96w2000hmsr7HAM', plate_flat_96: 'P96w360ijet9COS', plate_black_96: 'P96w360dmqt1COS', plate_384: 'P384w112dm8qnCOS',
  reservoir_60: 'C5pREAGENTijbvxHAM', tubes_24: 'C24p1ckjvwHAM', magnet: 'C1p1fmsrtHAM'
};
const title = o => String(o.displayName || o.name).trim();

const labware = {};
cat.slice().sort((a, b) => title(a).toLowerCase().localeCompare(title(b).toLowerCase())).forEach(o => {
  const label = title(o).length <= 60 ? title(o) : title(o).slice(0, 59) + '…';
  const key = `c_${o.id}`;
  if (o.classification === 'plate' && o.rows * o.columns > 1) labware[key] = { label, kind: 'plate', rows: o.rows, cols: o.columns, cap: o.volume || 1 };
  else if (o.classification === 'tiprack') labware[key] = { label, kind: 'tips', rows: o.rows, cols: o.columns, tipVol: o.volume };
  else if (o.classification === 'carrier' && o.rows === 4 && o.columns === 6) labware[key] = { label, kind: 'tubes', rows: 4, cols: 6, cap: 1500 };
});

// Everything the Prep lists, with its real ids (270 labware), so ids can always be resolved exactly as the converter does. Only LABWARE above is offered.
const all = cat.map(o => ({ id: o.id, name: o.name, displayName: title(o), classification: o.classification, rows: o.rows, columns: o.columns, volume: o.volume, containerName: o.containerName || '' }));
const builtin = {};
Object.entries(BUILTIN).forEach(([k, name]) => {
  const o = cat.find(x => x.name === name);
  if (!o) throw new Error(`built-in ${k} points at ${name}, which is not in the catalogue`);
  builtin[k] = { id: o.id, name: o.name, label: title(o) };
});

const out = `// ═══════════════════════════════════════════════════════
// GENERATED by scripts/build-prep-catalogue.js from the Prep's own labware and liquid
// exports. Do not edit by hand. The Builder and the converter offer only this labware
// and only these liquid classes; nothing else is accepted.
//
//   LABWARE   c_<Prep id> -> { label, kind, rows, cols, cap | tipVol }: plates, tip racks and 24-tube racks
//   BUILTIN   built-in key (tips_300, plate_pcr, ...) -> the catalogue entry it is compiled to
//   LIQUIDS   the Prep's liquid class names, in the Prep's order; LIQUID_CLASSES the same with the Prep's ids
//   ALL       every labware the Prep lists with its real id (only LABWARE is offered; ALL is for resolving ids)
// ═══════════════════════════════════════════════════════
(function (root, factory) {
  if (typeof module === 'object' && module.exports) module.exports = factory();
  else (root.PrepCalc = root.PrepCalc || {}).prepCatalogue = factory();
})(typeof self !== 'undefined' ? self : this, function () {
  const LABWARE = ${JSON.stringify(labware, null, 0).replace(/\},"c_/g, '},\n    "c_').replace(/^\{/, '{\n    ').replace(/\}$/, '\n  }')};
  const BUILTIN = ${JSON.stringify(builtin, null, 0).replace(/\},"/g, '},\n    "').replace(/^\{/, '{\n    ').replace(/\}$/, '\n  }')};
  const LIQUID_CLASSES = ${JSON.stringify(liq.map(x => ({ id: x.id, name: x.name })))};
  const LIQUIDS = LIQUID_CLASSES.map(l => l.name);
  const ALL = ${JSON.stringify(all)};
  /** The Prep's spelling of liquid class \`name\` (case-insensitive), or null. */
  const findLiquid = name => { const s = String(name === undefined || name === null ? '' : name).trim().toLowerCase(); return LIQUIDS.find(l => l.toLowerCase() === s) || null; };
  return { LABWARE, BUILTIN, LIQUIDS, LIQUID_CLASSES, ALL, findLiquid };
});
`;
const target = path.join(__dirname, '..', 'web', 'prep-catalogue.js');
fs.writeFileSync(target, out);
console.log(`wrote ${target}: ${Object.keys(labware).length} labware, ${liq.length} liquid classes`);
